def parse_judge(text: str) -> dict[str, bool] | None:
    content = text or ""
    m = re.search(r"```(?:json)?\s*(.*?)\s*```", content, re.S)
    if m:
        content = m.group(1)
    else:
        a, b = content.find("{"), content.rfind("}")
        content = content[a:b + 1] if a != -1 and b > a else content
    try:
        obj = json.loads(content)
    except (ValueError, TypeError):
        return None
    if not isinstance(obj, dict):
        return None
    out = {}
    for d in DIMS:
        v = (obj.get(f"{d}_eval") or {}).get("pass") if isinstance(obj.get(f"{d}_eval"), dict) else None
        if isinstance(v, str) and v.strip().lower() in ("true", "false"):
            v = v.strip().lower() == "true"
        if not isinstance(v, bool):
            return None
        out[d] = v
    return out


def score(rows: list[dict]) -> dict:
    out: dict = {}
    for typ in TYPES:
        rs = [r for r in rows if r["type"] == typ]
        for d in DIMS:
            out[f"{typ}_{d}"] = 100 * sum(r["pass"][d] for r in rs) / len(rs) if rs else 0.0
        out[f"{typ}"] = 100 * sum(r["pass"][d] for r in rs for d in DIMS) / (3 * len(rs)) if rs else 0.0
    for d in DIMS:
        out[d] = 100 * sum(r["pass"][d] for r in rows) / len(rows) if rows else 0.0
    out["overall"] = 100 * sum(r["pass"][d] for r in rows for d in DIMS) / (3 * len(rows)) if rows else 0.0
    out["n"] = len(rows)
    return out


def record(uid: str, k: int) -> Record:
    sc = by_uid()[uid]
    return session_record(sc["haystack_session"][k], sc["timestamps"][k])


def add_session(store: Store, facts: dict, uid: str, k: int) -> None:
    add_facts(store, facts, f"{uid}#{k}", day(by_uid()[uid]["timestamps"][k]), turn_texts(record(uid, k)), VERSION)


def build_store(uid: str, upto: int, facts_of) -> Store:
    store = Store()
    for k in range(upto):
        f = facts_of(uid, k)
        if f is not None:
            add_session(store, f, uid, k)
    return store
